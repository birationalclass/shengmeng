import {readFileSync,writeFileSync,statSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {posix} from 'node:path';
const root=new URL('./',import.meta.url),base=new URL('https://refuge.invalid/visuals/math-refuge/');
const html=readFileSync(new URL('index.html',root),'utf8');
const imports=JSON.parse(html.match(/<script type="importmap">([\s\S]*?)<\/script>/)[1]).imports;
const mappings=Object.entries(imports).map(([key,value])=>[key.startsWith('.')?new URL(key,base).href:key,new URL(value,base).href]).sort((a,b)=>b[0].length-a[0].length);
const resources=new Map(),visited=new Set();
function disk(url){return new URL(url.pathname.slice(1),new URL('../../',root));}
function add(url){
 const file=disk(url);let bytes=statSync(file).size;
 if(/\.(?:html|js|mjs|css|json|svg)$/.test(url.pathname))bytes=Buffer.byteLength(readFileSync(file,'utf8').replace(/\r\n/g,'\n'));
 resources.set(url.pathname,{url:posix.relative(base.pathname,url.pathname),bytes});
}
function resolve(spec,parent){
 const key=spec.startsWith('.')||spec.startsWith('/')?new URL(spec,parent).href:spec;
 for(const [from,to] of mappings){if(key===from)return new URL(to);if(from.endsWith('/')&&key.startsWith(from))return new URL(key.slice(from.length),to);}
 return new URL(spec,parent);
}
function module(url){
 if(visited.has(url.href))return;visited.add(url.href);add(url);
 const source=readFileSync(disk(url),'utf8');
 for(const match of source.matchAll(/(?:^|[;\r\n])\s*(?:import|export)\s*(?:(?:[^;'"\r\n]*?)\bfrom\s*)?['"]([^'"]+)['"]/g))module(resolve(match[1],url));
}
add(new URL('index.html',base));
for(const match of html.matchAll(/<link\b[^>]*rel="stylesheet"[^>]*href="([^"]+)"/g))add(new URL(match[1],base));
for(const match of html.matchAll(/<script\b([^>]*)src="([^"]+)"/g)){const url=new URL(match[2],base);if(/type="module"/.test(match[1]))module(url);else add(url);}
module(new URL(html.match(/import\('([^']*app\.js[^']*)'\)/)[1],base));
// Resources explicitly awaited by the default opening. Audio and deferred scenery stay on demand.
for(const name of ['../ocean/elliptic-distance.png','assets/waternormals.jpg'])add(new URL(name,base));
const output=new URL('startup-resources.js',root);
const standaloneManifest=resources.has(new URL('startup-resources.js',base).pathname);
// Include this manifest's own size without an unstable timestamp or recursive scan.
for(let i=0;i<8;i++){
 const source='// Generated by node build-startup-resources.mjs. Sizes are uncompressed bytes.\nexport const STARTUP_RESOURCES='+JSON.stringify([...resources.values()].sort((a,b)=>a.url.localeCompare(b.url)))+';\n';
 writeFileSync(output,source);if(!standaloneManifest)break;const old=resources.get(new URL('startup-resources.js',base).pathname)?.bytes;add(new URL('startup-resources.js',base));if(old===Buffer.byteLength(source))break;
}
console.log(JSON.stringify({files:resources.size,bytes:[...resources.values()].reduce((sum,item)=>sum+item.bytes,0),manifest:fileURLToPath(output)}));
