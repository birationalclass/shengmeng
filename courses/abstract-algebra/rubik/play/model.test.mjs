import assert from 'node:assert/strict';
import {createCube,FACES,NORMALS,identity,compose,inverse,equal,power,cycles,order,analyze} from './cube-model.mjs';
let checks=0;
const check=(condition,message)=>{assert.ok(condition,message);checks++;};
function exactOrder(p,label){
 const k=order(p);check(equal(power(p,k),identity(p.length)),`${label}: g^ord(g)=e`);
 let remaining=k;
 for(let prime=2n;prime*prime<=remaining;prime++)if(remaining%prime===0n){check(!equal(power(p,k/prime),identity(p.length)),`${label}: minimal at factor ${prime}`);while(remaining%prime===0n)remaining/=prime;}
 if(remaining>1n)check(!equal(power(p,k/remaining),identity(p.length)),`${label}: minimal at factor ${remaining}`);
}
// Independent Harvard GAP fixtures, not generated by this coordinate model.
const harvardFaces=['U','L','F','R','B','D'];
const harvardCycles=[[[1,3,8,6],[2,5,7,4],[9,33,25,17],[10,34,26,18],[11,35,27,19]],[[9,11,16,14],[10,13,15,12],[1,17,41,40],[4,20,44,37],[6,22,46,35]],[[17,19,24,22],[18,21,23,20],[6,25,43,16],[7,28,42,13],[8,30,41,11]],[[25,27,32,30],[26,29,31,28],[3,38,43,19],[5,36,45,21],[8,33,48,24]],[[33,35,40,38],[34,37,39,36],[3,9,46,32],[2,12,47,29],[1,14,48,27]],[[41,43,48,46],[42,45,47,44],[14,22,30,38],[15,23,31,39],[16,24,32,40]]];
const legacy=createCube(3);
const labels=harvardFaces.flatMap(f=>legacy.facelets.map((s,i)=>({s,i})).filter(({s})=>s.face===f&&!(s.row===1&&s.col===1)).map(({i})=>i));
for(let k=0;k<6;k++){
 const p=legacy.identity();for(const c of harvardCycles[k])c.forEach((n,i)=>{p[labels[n-1]]=labels[c[(i+1)%c.length]-1];});
 check(equal(p,legacy.movePermutation({face:harvardFaces[k],turns:1})),`Independent 3×3 ${harvardFaces[k]} turn`);
}
const rows=[];
for(let size=2;size<=5;size++){
 const cube=createCube(size),n=6*size*size,id=cube.identity(),alg=s=>cube.algorithmPermutation(cube.parse(s));
 check(cube.facelets.length===n,`${size}: complete facelets`);
 check(new Set(cube.facelets.map(s=>[...s.p,...s.n].join(','))).size===n,`${size}: no duplicate slots`);
 check(cube.facelets.every(s=>s.p.every(v=>Number.isInteger(v)&&Math.abs(v)<=size-1&&(v+size-1)%2===0)),`${size}: exact integral grid`);
 const pieces=new Map();cube.facelets.forEach((s,i)=>{const k=s.p.join(',');if(!pieces.has(k))pieces.set(k,[]);pieces.get(k).push(i);});
 for(const face of FACES)for(let depth=1;depth<=size;depth++)for(let width=1;width<=size-depth+1;width++){
  const move={face,depth,width,turns:1},p=cube.movePermutation(move),info=cube.moveInfo(move),name=cube.token(move);
  check(new Set(p).size===n&&p.every(v=>Number.isInteger(v)&&v>=0&&v<n),`${size}/${name}: bijective`);
  check(equal(power(p,4),id)&&order(p)===4n,`${size}/${name}: exact quarter-turn order`);
  check(equal(compose(p,cube.movePermutation({...move,turns:-1})),id),`${size}/${name}: inverse`);
  check(equal(compose(p,p),cube.movePermutation({...move,turns:2})),`${size}/${name}: half turn`);
  check(cube.token(cube.parse(name)[0])===name,`${size}/${name}: token round trip`);
  check(info.layers.length===width&&info.angle===-NORMALS[face][info.axis]*Math.PI/2,`${size}/${name}: animation agreement`);
  check([...pieces.values()].every(indices=>new Set(indices.map(i=>cube.facelets[p[i]].p.join(','))).size===1),`${size}/${name}: cubies remain intact`);
  const singles=Array.from({length:width},(_,i)=>({...move,depth:depth+i,width:1}));
  check(equal(cube.algorithmPermutation(singles),p),`${size}/${name}: multi-layer equals disjoint single layers`);
  const opposite=FACES.find(f=>NORMALS[f].every((v,j)=>v===-NORMALS[face][j]));
  check(equal(p,cube.movePermutation({face:opposite,depth:size-depth-width+2,width,turns:-1})),`${size}/${name}: opposite-face layer convention`);
 }
 check(order(alg('R'))===4n&&order(alg('R2'))===2n,`${size}: elementary orders`);
 check(order(alg('R U'))===[15n,105n,420n,420n][size-2],`${size}: RU reference order`);
 check(order(alg("R U R' U'"))===6n,`${size}: commutator reference order`);
 check(!equal(alg('R U'),alg('U R')),`${size}: noncommutativity`);
 check(equal(alg('[F:[2R,U]]'),alg("F 2R U 2R' U' F'")),`${size}: nested conjugate`);
 check(equal(alg('(R U)3'),alg('R U R U R U')),`${size}: repetition`);
 check(equal(alg("(R U)'"),alg("U' R'")),`${size}: inverse group`);
 check(equal(alg('r U'),alg('Rw U')),`${size}: lower-case wide alias`);
 check(equal(alg('R2′ U′'),alg("R2 U'")),`${size}: Unicode prime`);
 check(equal(alg(''),id)&&order(alg(''))===1n,`${size}: identity order`);
 const p=alg('R U 2R F2'),huge=1234567890123456789012345678901234567890n;
 check(equal(power(p,huge),power(p,huge%order(p))),`${size}: exact huge exponents`);
 check(equal(power(p,String(huge)),power(p,huge)),`${size}: decimal exponent input`);
 check(equal(power(p,-7n),power(inverse(p),7n)),`${size}: negative exponent`);
 exactOrder(p,`${size}/R U 2R F2`);exactOrder(alg('Rw U'),`${size}/Rw U`);
 const summary=analyze(p);check(summary.order===order(p)&&summary.moved+summary.fixed===n,`${size}: complete order analysis`);
 check(summary.cycleCounts.reduce((sum,c)=>sum+c.count*c.length,0)===summary.moved,`${size}: cycle multiplicities`);
 const copy=cube.movePermutation({face:'R'});copy[0]=-1;check(equal(cube.movePermutation({face:'R'}),alg('R')),`${size}: cache isolation`);
 for(const bad of ['X','R3','(R','[R,U','[R]','(R)99999','R;alert(1)','[R,]','0R','2-1R',`${size+1}R`,`${size+1}Rw`,'M','R2w','2-3Rw']){assert.throws(()=>cube.parse(bad),undefined,`${size}: reject ${bad}`);checks++;}
 assert.throws(()=>cube.parse('('.repeat(40)+'R'+')'.repeat(40)));checks++;
 assert.throws(()=>cube.parse('(R U)20',{limit:30}));checks++;
 rows.push({size,RU:String(order(alg('R U'))),commutator:String(order(alg('[R,U]'))),inner:String(order(alg('2R U'))),wide:String(order(alg('Rw U')))});
}
